/** 'YYYY-MM-DD' → 「M月D日（曜）」。曜日は weekdayJst で計算する（文に直書きしない）。形がちがえばそのまま返す */
function dateWithWeekday(iso: string): string {
  if (!isIsoDate(iso)) return iso;
  const [, m, d] = iso.split('-').map(Number);
  return `${m}月${d}日（${'日月火水木金土'[weekdayJst(iso)]}）`;
}

/** ひな形の {整理番号}・{残り}・{期限}・{送り直しURL} を世帯の値で埋める */
export function fillLineReply(text: string, d: { refCode: string; remaining: number; payDue: string; resendUrl: string }): string {
  return text
    .replaceAll('{整理番号}', d.refCode)
    .replaceAll('{残り}', `${d.remaining.toLocaleString('ja-JP')}円`)
    .replaceAll('{期限}', dateWithWeekday(d.payDue))
    .replaceAll('{送り直しURL}', d.resendUrl);
}
